FONT_BOLD = "jetbrains-mono/JetBrainsMono-Bold.ttf"
FONT_EBOLD = "jetbrains-mono/JetBrainsMono-ExtraBold.ttf"
FONT_REG = "jetbrains-mono/JetBrainsMono-Regular.ttf"

BG = "background.png"

# --- per-core grid coordinates -------------------------------------------
PC_X0 = 10
PC_Y0 = 72       # row 0 top
PC_Y1 = 84       # row 1 top
PC_W = 15
PC_H = 8
PC_DX = 19       # column stride


def percore_block() -> str:
    lines = ["  CUSTOM:", "    INTERVAL: 1"]
    for i in range(32):
        row = 0 if i < 16 else 1
        col = i if i < 16 else i - 16
        x = PC_X0 + col * PC_DX
        y = PC_Y0 if row == 0 else PC_Y1
        lines.append(f"    CpuCore{i:02d}:")
        lines.append(f"      GRAPH:")
        lines.append(f"        SHOW: True")
        lines.append(f"        X: {x}")
        lines.append(f"        Y: {y}")
        lines.append(f"        WIDTH: {PC_W}")
        lines.append(f"        HEIGHT: {PC_H}")
        lines.append(f"        MIN_VALUE: 0")
        lines.append(f"        MAX_VALUE: 100")
        lines.append(f"        BAR_COLOR: {ACCENT}")
        lines.append(f"        BAR_OUTLINE: False")
        lines.append(f"        BACKGROUND_COLOR: {BAR_BG}")
    return "\n".join(lines)


# --- main theme body ------------------------------------------------------
def text(*, x, y, font, size, color, anchor="lt", show_unit=True, indent=8):
    """Build an indented TEXT stanza. Avoids WIDTH (which fights anchor=rt: it makes
    DisplayText treat the right edge as X+WIDTH, pushing right-anchored text off-screen).
    `indent` is the column where keys should land; first line is positioned by the caller's
    interpolation site, subsequent lines are prefixed with `indent` spaces."""
    pad = " " * indent
    return dedent(f"""\
        SHOW: True
        SHOW_UNIT: {show_unit}
        X: {x}
        Y: {y}
        FONT: {font}
        FONT_SIZE: {size}
        FONT_COLOR: {color}
        BACKGROUND_IMAGE: {BG}
        ANCHOR: {anchor}""").replace("\n", "\n" + pad)


def bar(*, x, y, w, h, color=ACCENT, indent=8):
    pad = " " * indent
    return dedent(f"""\
        SHOW: True
        X: {x}
        Y: {y}
        WIDTH: {w}
        HEIGHT: {h}
        MIN_VALUE: 0
        MAX_VALUE: 100
        BAR_COLOR: {color}
        BAR_OUTLINE: False
        BACKGROUND_COLOR: {BAR_BG}""").replace("\n", "\n" + pad)


