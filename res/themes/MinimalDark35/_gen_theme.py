"""Generate theme.yaml for MinimalDark35 (writes the file in this directory).

Re-run after tweaking palette/layout constants below.
"""
from pathlib import Path
from textwrap import dedent

# --- palette / fonts ------------------------------------------------------
ACCENT = "95, 179, 214"          # cool cyan — used for bars and values
ACCENT_DIM = "70, 130, 160"
TXT = "224, 226, 230"            # primary text
TXT_DIM = "140, 144, 153"        # secondary
WARN = "232, 165, 70"            # for temps when hot (we use static here)
BAR_BG = "32, 35, 42"
